create table if not exists public.storefront_quotes (
  id integer generated by default as identity primary key,
  tenant_id integer not null references public.tenants(id) on delete cascade,
  customer_mobile text not null,
  total numeric(12, 2) not null check (total >= 0),
  status text not null default 'requested' check (status in ('requested', 'contacted', 'cancelled')),
  created_at timestamptz not null default now()
);

create table if not exists public.storefront_quote_items (
  id integer generated by default as identity primary key,
  tenant_id integer not null references public.tenants(id) on delete cascade,
  quote_id integer not null references public.storefront_quotes(id) on delete cascade,
  product_id integer references public.products(id) on delete set null,
  product_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(12, 2) not null check (unit_price >= 0),
  created_at timestamptz not null default now()
);

create index if not exists storefront_quotes_tenant_created_idx
  on public.storefront_quotes (tenant_id, created_at desc);
create index if not exists storefront_quote_items_quote_idx
  on public.storefront_quote_items (quote_id);

alter table public.storefront_quotes enable row level security;
alter table public.storefront_quote_items enable row level security;
revoke all on public.storefront_quotes from anon, authenticated;
revoke all on public.storefront_quote_items from anon, authenticated;
