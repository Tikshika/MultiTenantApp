-- Convert an empty UUID-based tenant schema to integer IDs and replace recursive
-- user policies. Populated UUID-based tenant schemas are refused, never coerced.
drop policy if exists "tenants are visible by tenant match" on public.tenants;
drop policy if exists "tenants are editable by super admin only" on public.tenants;
drop policy if exists "tenant settings are scoped by tenant" on public.tenant_settings;
drop policy if exists "users can view their own record or tenant members" on public.users;
drop policy if exists "users can update their own record" on public.users;
drop policy if exists "store owners can manage only their tenant users" on public.users;
drop policy if exists "tenant categories scoped by tenant" on public.categories;
drop policy if exists "tenant products scoped by tenant" on public.products;
drop policy if exists "public storefront products read" on public.products;
drop policy if exists "tenant orders scoped by tenant" on public.orders;
drop policy if exists "tenant order items scoped by tenant" on public.order_items;
drop policy if exists "tenant inventory logs scoped by tenant" on public.inventory_log;

do $$
declare
  id_types text[];
  tenant_tables text[] := array[
    'tenants',
    'tenant_settings',
    'users',
    'categories',
    'products',
    'orders',
    'order_items',
    'inventory_log'
  ];
  table_name text;
  has_rows boolean;
  foreign_key record;
begin
  select array_agg(actual.data_type order by expected.ordinality)
  into id_types
  from unnest(tenant_tables) with ordinality as expected(table_name, ordinality)
  left join information_schema.columns as actual
    on actual.table_schema = 'public'
   and actual.table_name = expected.table_name
   and actual.column_name = case when expected.table_name = 'tenants' then 'id' else 'tenant_id' end;

  if array_length(id_types, 1) <> array_length(tenant_tables, 1)
    or array_position(id_types, null) is not null then
    raise exception 'One or more tenant tables or ID columns are missing.';
  end if;

  if id_types = array_fill('uuid'::text, array[8]) then
    foreach table_name in array tenant_tables loop
      execute format('select exists (select 1 from public.%I limit 1)', table_name) into has_rows;
      if has_rows then
        raise exception
          'Cannot convert UUID tenant IDs because public.% contains rows. Migrate tenant IDs with an explicit ID mapping first.',
          table_name;
      end if;
    end loop;

    for foreign_key in
      select conrelid::regclass as relation_name, conname
      from pg_constraint
      where contype = 'f'
        and confrelid = 'public.tenants'::regclass
    loop
      execute format(
        'alter table %s drop constraint %I',
        foreign_key.relation_name,
        foreign_key.conname
      );
    end loop;

    alter table public.tenants alter column id drop default;
    alter table public.tenants alter column id type integer using null::integer;
    alter table public.tenants alter column id add generated by default as identity;

    alter table public.tenant_settings alter column tenant_id type integer using null::integer;
    alter table public.users alter column tenant_id type integer using null::integer;
    alter table public.categories alter column tenant_id type integer using null::integer;
    alter table public.products alter column tenant_id type integer using null::integer;
    alter table public.orders alter column tenant_id type integer using null::integer;
    alter table public.order_items alter column tenant_id type integer using null::integer;
    alter table public.inventory_log alter column tenant_id type integer using null::integer;

    alter table public.tenant_settings add constraint tenant_settings_tenant_id_fkey
      foreign key (tenant_id) references public.tenants(id) on delete cascade;
    alter table public.users add constraint users_tenant_id_fkey
      foreign key (tenant_id) references public.tenants(id) on delete set null;
    alter table public.categories add constraint categories_tenant_id_fkey
      foreign key (tenant_id) references public.tenants(id) on delete cascade;
    alter table public.products add constraint products_tenant_id_fkey
      foreign key (tenant_id) references public.tenants(id) on delete cascade;
    alter table public.orders add constraint orders_tenant_id_fkey
      foreign key (tenant_id) references public.tenants(id) on delete cascade;
    alter table public.order_items add constraint order_items_tenant_id_fkey
      foreign key (tenant_id) references public.tenants(id) on delete cascade;
    alter table public.inventory_log add constraint inventory_log_tenant_id_fkey
      foreign key (tenant_id) references public.tenants(id) on delete cascade;
  elsif id_types <> array_fill('integer'::text, array[8]) then
    raise exception 'Tenant ID columns have mixed or unsupported types: %', id_types;
  end if;
end;
$$;

drop function if exists public.current_tenant_id();
drop function if exists public.set_current_tenant(uuid);
drop function if exists public.set_current_tenant(integer);

create or replace function public.app_current_tenant_id()
returns integer
language sql
stable
set search_path = ''
as $$
  select nullif(current_setting('app.current_tenant_id', true), '')::integer;
$$;

create or replace function public.app_current_user_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select u.role from public.users as u where u.id = auth.uid() limit 1;
$$;

create or replace function public.app_current_user_tenant_id()
returns integer
language sql
stable
security definer
set search_path = ''
as $$
  select u.tenant_id from public.users as u where u.id = auth.uid() limit 1;
$$;

create function public.current_tenant_id()
returns integer
language sql
stable
as $$
  select public.app_current_tenant_id();
$$;

create function public.set_current_tenant(tenant_id integer)
returns text
language sql
security definer
as $$
  select set_config('app.current_tenant_id', tenant_id::text, true);
$$;

drop policy if exists "tenants are visible by tenant match" on public.tenants;
create policy "tenants are visible by tenant match"
on public.tenants
for select
using (id = public.app_current_tenant_id());

drop policy if exists "tenants are editable by super admin only" on public.tenants;
create policy "tenants are editable by super admin only"
on public.tenants
for all
using (public.app_current_user_role() = 'super_admin')
with check (public.app_current_user_role() = 'super_admin');

drop policy if exists "tenant settings are scoped by tenant" on public.tenant_settings;
create policy "tenant settings are scoped by tenant"
on public.tenant_settings
for all
using (tenant_id = public.app_current_tenant_id())
with check (tenant_id = public.app_current_tenant_id());

drop policy if exists "users can view their own record or tenant members" on public.users;
create policy "users can view their own record or tenant members"
on public.users
for select
using (
  id = auth.uid()
  or tenant_id = public.app_current_tenant_id()
  or public.app_current_user_role() = 'super_admin'
);

drop policy if exists "users can update their own record" on public.users;
create policy "users can update their own record"
on public.users
for update
using (id = auth.uid())
with check (id = auth.uid());

drop policy if exists "store owners can manage only their tenant users" on public.users;
create policy "store owners can manage only their tenant users"
on public.users
for all
using (
  tenant_id = public.app_current_user_tenant_id()
  and public.app_current_user_role() = 'store_owner'
)
with check (
  tenant_id = public.app_current_user_tenant_id()
  and public.app_current_user_role() = 'store_owner'
);

drop policy if exists "tenant categories scoped by tenant" on public.categories;
create policy "tenant categories scoped by tenant"
on public.categories
for all
using (tenant_id = public.app_current_tenant_id())
with check (tenant_id = public.app_current_tenant_id());

drop policy if exists "tenant products scoped by tenant" on public.products;
create policy "tenant products scoped by tenant"
