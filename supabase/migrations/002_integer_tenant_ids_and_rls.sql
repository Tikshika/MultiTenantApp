drop policy if exists "public storefront products read" on public.products;
create policy "public storefront products read"
on public.products
for select
using (
  is_active = true
  and tenant_id = public.app_current_tenant_id()
);

drop policy if exists "tenant orders scoped by tenant" on public.orders;
