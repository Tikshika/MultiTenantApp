create table if not exists public.tenant_hero_images (
  id integer generated by default as identity primary key,
  tenant_id integer not null references public.tenants(id) on delete cascade,
  image_path text not null,
  position integer not null check (position >= 0),
  created_at timestamptz not null default now(),
  constraint tenant_hero_images_tenant_path_unique unique (tenant_id, image_path)
);

create index if not exists tenant_hero_images_tenant_position_idx
  on public.tenant_hero_images (tenant_id, position, id);

alter table public.tenant_hero_images enable row level security;
revoke all on public.tenant_hero_images from anon, authenticated;
