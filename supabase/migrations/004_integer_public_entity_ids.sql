create policy "tenants are editable by super admin only"
on public.tenants
for all
using (public.app_current_user_role() = 'super_admin')
with check (public.app_current_user_role() = 'super_admin');

create policy "users can view their own record or tenant members"
on public.users
for select
using (
  auth_user_id = auth.uid()::text
  or tenant_id = public.app_current_tenant_id()
  or public.app_current_user_role() = 'super_admin'
);

create policy "users can update their own record"
on public.users
for update
using (auth_user_id = auth.uid()::text)
with check (auth_user_id = auth.uid()::text);

create policy "store owners can manage only their tenant users"
on public.users
for all
using (
  tenant_id = public.app_current_user_tenant_id()
  and public.app_current_user_role() = 'store_owner'
)
with check (
  tenant_id = public.app_current_user_tenant_id()
  and public.app_current_user_role() = 'store_owner'
);
