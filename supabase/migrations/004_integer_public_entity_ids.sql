-- Replace UUID columns in the application schema with integer IDs.
-- The users table keeps the Supabase Auth user identifier as text.
do $$
declare
  table_name text;
  has_rows boolean;
begin
  foreach table_name in array array[
    'users',
    'categories',
    'products',
    'orders',
    'order_items',
    'inventory_log'
  ] loop
    if to_regclass(format('public.%I', table_name)) is null then
      raise exception 'Required table public.% is missing.', table_name;
    end if;

    execute format('select exists (select 1 from public.%I limit 1)', table_name)
      into has_rows;
    if has_rows then
      raise exception
        'Cannot convert UUID IDs because public.% contains rows. Export and map existing IDs and foreign keys before migrating.',
        table_name;
    end if;
  end loop;
end;
$$;

