create table if not exists public.admin_accounts (
  id integer generated by default as identity primary key,
  email text not null,
  password_hash text not null,
  role text not null check (role in ('store_owner', 'super_admin')),
  tenant_id integer references public.tenants(id) on delete cascade,
  must_change_password boolean not null default true,
  created_at timestamptz not null default now(),
  password_changed_at timestamptz not null default now(),
  constraint admin_accounts_role_tenant_check check (
    (role = 'store_owner' and tenant_id is not null)
    or (role = 'super_admin' and tenant_id is null)
  )
);

create unique index if not exists admin_accounts_email_lower_idx
  on public.admin_accounts (lower(email));

create table if not exists public.admin_sessions (
  token_hash text primary key,
  admin_account_id integer not null references public.admin_accounts(id) on delete cascade,
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

create index if not exists admin_sessions_expiration_idx
  on public.admin_sessions (expires_at);

alter table public.admin_accounts enable row level security;
alter table public.admin_sessions enable row level security;

revoke all on public.admin_accounts from anon, authenticated;
revoke all on public.admin_sessions from anon, authenticated;
