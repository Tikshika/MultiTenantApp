-- Multi-tenant retail platform schema for Supabase
-- One database, many tenants, row-level security enforced per tenant.

create extension if not exists "pgcrypto";

create table if not exists public.tenants (
  id integer generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  subdomain text not null unique,
  category text not null check (category in ('pharmacy', 'hardware', 'grocery', 'general')),
  theme_color text not null default '#0f172a',
  currency text not null default 'INR',
  status text not null default 'active' check (status in ('active', 'suspended', 'archived')),
  created_at timestamptz not null default now()
);

create table if not exists public.tenant_settings (
  tenant_id integer primary key references public.tenants(id) on delete cascade,
  display_name text not null,
  logo_url text,
  theme_color text,
  currency text,
  category text,
  contact_email text,
  contact_phone text,
  homepage_banner text,
  feature_prescription_upload boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.users (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null unique,
  role text not null check (role in ('customer', 'store_owner', 'super_admin')),
  tenant_id integer references public.tenants(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(),
  tenant_id integer not null references public.tenants(id) on delete cascade,
  name text not null,
  parent_id uuid references public.categories(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists idx_categories_tenant_id on public.categories(tenant_id);
create index if not exists idx_categories_parent_id on public.categories(parent_id);

create table if not exists public.products (
  id uuid primary key default gen_random_uuid(),
  tenant_id integer not null references public.tenants(id) on delete cascade,
  category_id uuid references public.categories(id) on delete set null,
  name text not null,
  description text,
  price numeric(12,2) not null check (price >= 0),
  stock_qty integer not null default 0 check (stock_qty >= 0),
  image_url text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create index if not exists idx_products_tenant_id on public.products(tenant_id);
create index if not exists idx_products_category_id on public.products(category_id);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  tenant_id integer not null references public.tenants(id) on delete cascade,
  user_id uuid not null references public.users(id),
  status text not null default 'pending' check (status in ('pending', 'received', 'packed', 'shipped', 'delivered', 'cancelled')),
  total numeric(12,2) not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists idx_orders_tenant_id on public.orders(tenant_id);
create index if not exists idx_orders_user_id on public.orders(user_id);

create table if not exists public.order_items (
  id uuid primary key default gen_random_uuid(),
  tenant_id integer not null references public.tenants(id) on delete cascade,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id uuid not null references public.products(id),
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0),
  created_at timestamptz not null default now()
);

create index if not exists idx_order_items_tenant_id on public.order_items(tenant_id);
create index if not exists idx_order_items_order_id on public.order_items(order_id);

create table if not exists public.inventory_log (
  id uuid primary key default gen_random_uuid(),
  tenant_id integer not null references public.tenants(id) on delete cascade,
  product_id uuid not null references public.products(id),
  change_qty integer not null,
  reason text,
  created_at timestamptz not null default now()
);

create index if not exists idx_inventory_log_tenant_id on public.inventory_log(tenant_id);
create index if not exists idx_inventory_log_product_id on public.inventory_log(product_id);

-- Tenant context helper for request-scoped security checks.
create or replace function public.current_tenant_id()
returns integer
language sql
stable
as $$
  select nullif(current_setting('app.current_tenant_id', true), '')::integer;
$$;

create or replace function public.set_current_tenant(tenant_id integer)
returns text
language sql
security definer
as $$
  select set_config('app.current_tenant_id', tenant_id::text, true);
$$;

create or replace function public.current_user_role()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select u.role from public.users as u where u.id = auth.uid() limit 1;
$$;

create or replace function public.current_user_tenant_id()
returns integer
language sql
stable
security definer
set search_path = ''
as $$
  select u.tenant_id from public.users as u where u.id = auth.uid() limit 1;
$$;

-- Enable RLS for all tenant-scoped tables.
alter table public.tenants enable row level security;
alter table public.tenant_settings enable row level security;
alter table public.users enable row level security;
alter table public.categories enable row level security;
alter table public.products enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.inventory_log enable row level security;

-- Basic tenant helper: a store owner can manage only their tenant.
create policy "tenants are visible by tenant match"
on public.tenants
for select
using (id = public.current_tenant_id());

create policy "tenants are editable by super admin only"
on public.tenants
for all
using (
  public.current_user_role() = 'super_admin'
)
with check (
  public.current_user_role() = 'super_admin'
);

create policy "tenant settings are scoped by tenant"
on public.tenant_settings
for all
using (tenant_id = public.current_tenant_id())
with check (tenant_id = public.current_tenant_id());

create policy "users can view their own record or tenant members"
on public.users
for select
using (
  id = auth.uid()
  or tenant_id = public.current_tenant_id()
  or public.current_user_role() = 'super_admin'
);

create policy "users can update their own record"
on public.users
for update
using (id = auth.uid())
with check (id = auth.uid());

create policy "store owners can manage only their tenant users"
on public.users
for all
using (
  tenant_id = public.current_user_tenant_id()
  and public.current_user_role() = 'store_owner'
)
with check (
  tenant_id = public.current_user_tenant_id()
  and public.current_user_role() = 'store_owner'
);

create policy "tenant categories scoped by tenant"
on public.categories
for all
using (tenant_id = public.current_tenant_id())
with check (tenant_id = public.current_tenant_id());

create policy "tenant products scoped by tenant"
on public.products
for all
using (tenant_id = public.current_tenant_id())
with check (tenant_id = public.current_tenant_id());

create policy "tenant orders scoped by tenant"
on public.orders
for all
using (tenant_id = public.current_tenant_id())
with check (tenant_id = public.current_tenant_id());

create policy "tenant order items scoped by tenant"
on public.order_items
for all
using (tenant_id = public.current_tenant_id())
with check (tenant_id = public.current_tenant_id());

create policy "tenant inventory logs scoped by tenant"
on public.inventory_log
for all
using (tenant_id = public.current_tenant_id())
with check (tenant_id = public.current_tenant_id());

-- Allow public product browsing for storefront reads.
create policy "public storefront products read"
on public.products
for select
using (
  is_active = true
  and tenant_id = public.current_tenant_id()
);

-- Example trigger to keep tenant_settings updated_at fresh.
create or replace function public.update_tenant_settings_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger tenant_settings_updated_at
before update on public.tenant_settings
for each row
execute function public.update_tenant_settings_updated_at();

-- Helpful indexes for performance.
create index if not exists idx_users_tenant_id on public.users(tenant_id);
create index if not exists idx_users_role on public.users(role);
create index if not exists idx_orders_status on public.orders(status);
create index if not exists idx_products_active on public.products(is_active);
